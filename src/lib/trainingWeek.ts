/** رقم خطوة اليوم (1..7) أو null إن انقضى الأسبوع */
export function currentTrainingStep(startMs: number | undefined, nowMs: number): number | null {
  if (!startMs) return null;
  const day = Math.floor((nowMs - startMs) / 86400000) + 1;
  return day >= 1 && day <= TRAINING_STEPS.length ? day : null;
}
