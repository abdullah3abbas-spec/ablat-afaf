/** إيجاد درس بالرمز */
export function bookLessonByCode(code: string): { unit: BookUnitMeta; lesson: BookLessonMeta } | undefined {
  for (const unit of BOOK_UNITS) {
    const lesson = unit.lessons.find((l) => l.code === code);
    if (lesson) return { unit, lesson };
  }
  return undefined;
}

/** إيجاد درس بعنوانه الحرفي */
export function bookLessonByTitle(title: string): { unit: BookUnitMeta; lesson: BookLessonMeta } | undefined {
  for (const unit of BOOK_UNITS) {
    const lesson = unit.lessons.find((l) => l.title === title);
    if (lesson) return { unit, lesson };
  }
  return undefined;
}
